export interface GiftShieldResult {
  safe: string
  hits: string[]
  clean: boolean
}

declare const __DEV__: boolean
const isDev = typeof __DEV__ !== 'undefined' ? __DEV__ : process.env.NODE_ENV !== 'production'

/** 过滤礼品类文案：屏蔽医疗 / 迷信疗效宣称，吉祥话（平安 / 好运等）放行 */
export function giftShieldCopy(text: string): GiftShieldResult {
  if (!text) return { safe: text, hits: [], clean: true }
  let safe = text
  const hits: string[] = []
  for (const w of GIFT_FORBIDDEN_WORDS) {
    if (safe.includes(w)) {
      hits.push(w)
      const repl = GIFT_SAFE_REPLACEMENT[w]
      safe = repl ? safe.split(w).join(repl) : safe.split(w).join('**')
    }
  }
  if (hits.length && isDev) {
    // eslint-disable-next-line no-console
    console.warn('[gift-shield] 命中违禁词已屏蔽:', hits.join(', '), '| 原文:', text)
  }
  return { safe, hits, clean: hits.length === 0 }
}

/** 仅校验是否含违禁词（商家端提交前拦截） */
export function hasGiftForbidden(text: string): boolean {
  return GIFT_FORBIDDEN_WORDS.some((w) => text.includes(w))
}
