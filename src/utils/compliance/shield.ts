export interface ShieldResult {
  /** 过滤后的安全文案 */
  safe: string
  /** 命中的违禁词列表 */
  hits: string[]
  /** 是否完全干净（无命中） */
  clean: boolean
}

declare const __DEV__: boolean
const isDev = typeof __DEV__ !== 'undefined' ? __DEV__ : process.env.NODE_ENV !== 'production'

/**
 * 过滤文案：屏蔽医疗宣称违禁词。
 * - 有安全近义词 → 替换
 * - 无映射 → 脱敏为 **
 * - dev 环境打印命中留痕
 */
export function shieldCopy(text: string): ShieldResult {
  if (!text) return { safe: text, hits: [], clean: true }
  let safe = text
  const hits: string[] = []
  for (const w of FORBIDDEN_WORDS) {
    if (safe.includes(w)) {
      hits.push(w)
      const repl = SAFE_REPLACEMENT[w]
      safe = repl ? safe.split(w).join(repl) : safe.split(w).join('**')
    }
  }
  if (hits.length && isDev) {
    // eslint-disable-next-line no-console
    console.warn('[compliance-shield] 命中违禁词已屏蔽:', hits.join(', '), '| 原文:', text)
  }
  return { safe, hits, clean: hits.length === 0 }
}

/** 仅校验是否含违禁词（用于提交前 / 构建期拦截） */
export function hasForbidden(text: string): boolean {
  return FORBIDDEN_WORDS.some((w) => text.includes(w))
}

/**
 * 受众 / 人群标签过滤：剔除「体弱 / 术后 / 调养期 / 进补 / 气血偏弱」等
 * 疾病定向或恢复期待词（PRD 2.1 / 3.3 严禁对人群做疾病适配宣称），
 * 其余标签经 shieldCopy 脱敏后保留。用于商品详情页「适合谁 / 人群标签 / 食用小贴士」。
 */
const AUDIENCE_FORBIDDEN = /(体弱|术后|调养期|进补|气血偏弱|经期后|病后|体虚|虚弱|恢复中|康复期|慢病|慢性|病症|调理|滋补|补益|温补|温养|滋养)/

export function cleanAudienceTags(list?: string[] | null): string[] {
  if (!list || !list.length) return []
  const out: string[] = []
  const seen = new Set<string>()
  for (const raw of list) {
    const t = shieldCopy((raw || '').trim()).safe
    if (!t) continue
    if (AUDIENCE_FORBIDDEN.test(t)) continue
    if (seen.has(t)) continue
    seen.add(t)
    out.push(t)
  }
  return out
}
