const ALL_SENSITIVE = [
  ...MEDICAL_SENSITIVE_WORDS,
  ...EXAGGERATION_SENSITIVE_WORDS,
  ...DISTRIBUTION_SENSITIVE_WORDS,
]

/**
 * 检测文案是否包含敏感词
 * @param text 待检测文案
 * @returns 含敏感词列表，无则返回空数组
 */
export function detectSensitiveWords(text: string): string[] {
  const found: string[] = []
  for (const word of ALL_SENSITIVE) {
    if (text.includes(word)) found.push(word)
  }
  return found
}

/**
 * 快速判断文案是否有风险（保守检测，精确匹配）
 */
export function isRisky(text: string): boolean {
  return detectSensitiveWords(text).length > 0
}

/**
 * 替换违规词（简单全局替换，不支持正则）
 */
export function sanitizeText(text: string, type: 'medical' | 'exaggeration' | 'distribution' | 'all' = 'all'): string {
  const map = type === 'medical' ? MEDICAL_FORBIDDEN
    : type === 'exaggeration' ? EXAGGERATION_FORBIDDEN
    : type === 'distribution' ? DISTRIBUTION_FORBIDDEN
    : { ...MEDICAL_FORBIDDEN, ...EXAGGERATION_FORBIDDEN, ...DISTRIBUTION_FORBIDDEN }

  let result = text
  for (const [bad, good] of Object.entries(map)) {
    if (!bad.includes('.*')) {
      result = result.replace(new RegExp(bad, 'g'), good)
    }
  }
  return result
}

/**
 * 获取特定人群的合规文案模板
 * @param type 高血压 | 糖尿病 | 儿童
 */
export function getGroupDisclaimer(type: 'hypertension' | 'diabetes' | 'children'): string {
  if (type === 'hypertension') return `供血压管控人群饮食参考，建议少量食用，结合自身情况取舍。${FOOD_DISCLAIMER}`
  if (type === 'diabetes') return `供糖分管控人群饮食参考，请留意配料碳水含量。${FOOD_DISCLAIMER}`
  if (type === 'children') return `适合孩童日常零食，均衡膳食更重要。${FOOD_DISCLAIMER}`
  return FOOD_DISCLAIMER
}
